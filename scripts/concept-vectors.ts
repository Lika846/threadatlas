/**
 * `npm run concepts:embed` — regenerates `src/lib/semantic/topics/concept-vectors.generated.ts`,
 * the vectors of the theme-naming vocabulary (`concepts.ts`), with the installed local model.
 *
 * Run it after editing the vocabulary (and bumping `CONCEPTS_VERSION`) or changing the model.
 * Offline: it starts the production inference child on the installed model; nothing is
 * downloaded. Each name is embedded as a search query and stored int8-quantised, as the index
 * stores passages. The file records the embedding version and a hash of the names; the atlas
 * uses it only when both match the running code (`concept-names.ts`).
 *
 * Run by Node 24 directly (type stripping): relative `.ts` imports, erasable syntax only.
 */
import fs from "node:fs";
import path from "node:path";
import { InferenceProcess, productionChildEntry } from "../src/lib/semantic/inference-process.ts";
import { resolveModelDir } from "../src/lib/semantic/model-files.ts";
import { EMBEDDING_VERSION } from "../src/lib/semantic/model-manifest.ts";
import { quantizeInt8 } from "../src/lib/semantic/quantize.ts";
import { CONCEPTS, CONCEPTS_VERSION } from "../src/lib/semantic/topics/concepts.ts";
import { conceptsHash } from "../src/lib/semantic/topics/concept-names.ts";

const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "src/lib/semantic/topics/concept-vectors.generated.ts");

const p = await InferenceProcess.start({ entry: productionChildEntry(root), modelDir: resolveModelDir({ env: process.env, root }) });
const vectors: string[] = [];
try {
  for (const c of CONCEPTS) vectors.push(Buffer.from(quantizeInt8(await p.embedQuery(c.name))).toString("base64"));
} finally {
  await p.close();
}
const body = `// Generated by \`npm run concepts:embed\` (scripts/concept-vectors.ts). Do not edit by hand.
// The theme-naming vocabulary (concepts.ts), embedded as queries by the local model, int8-quantised.
import type { ConceptVectorFile } from "./concepts.ts";

export const CONCEPT_VECTORS: ConceptVectorFile = {
  conceptsVersion: ${CONCEPTS_VERSION},
  embeddingVersion: ${JSON.stringify(EMBEDDING_VERSION)},
  namesHash: ${JSON.stringify(conceptsHash(CONCEPTS))},
  vectors: [
${vectors.map((v) => `    ${JSON.stringify(v)},`).join("\n")}
  ],
};
`;
fs.writeFileSync(out, body);
console.log(`${CONCEPTS.length} concept vectors written to ${path.relative(root, out)}`);
